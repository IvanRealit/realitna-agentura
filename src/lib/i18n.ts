export type RouteKey = keyof typeof routes;
export function href(l: Locale, key?: RouteKey, slug?: string) {
  return `/${l}${key ? `/${routes[key][l]}` : ""}${slug ? `/${slug}` : ""}`;
}
export function routeKey(l: Locale, path?: string) {
  return (Object.keys(routes) as RouteKey[]).find((k) => routes[k][l] === path);
}
export function translation(
  value: unknown,
  l: Locale,
): { title: string; description: string } {
  const v = value as Record<
    string,
    { title?: string; description?: string }
  > | null;
  const t = v?.[l] ?? v?.sk ?? {};
  return { title: t.title ?? "", description: t.description ?? "" };
}
